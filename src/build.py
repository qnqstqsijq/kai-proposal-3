def render_doc(spec):
    h = spec["hero"]
    toc = "".join(f'<a href="#{sid}">{esc(t)}</a>' for sid, t, _ in spec["docsecs"])
    secs = []
    for sid, t, c in spec["docsecs"]:
        parts = []
        if c.get("facts"):
            parts.append('<ul class="facts">' + "".join(f"<li><b>{esc(k)}</b><span>{esc(v)}</span></li>" for k, v in c["facts"]) + "</ul>")
        for p in c.get("p", []):
            parts.append(f"<p>{esc(p)}</p>")
        if c.get("ul"):
            parts.append("<ul>" + "".join((f"<li><b>{esc(x[0])}</b> {esc(x[1])}</li>" if isinstance(x, tuple) else f"<li>{esc(x)}</li>") for x in c["ul"]) + "</ul>")
        if c.get("cta"):
            parts.append(f'<div class="doclinks" style="margin-top:20px">{alink(c["cta"][0], c["cta"][1], cls="")}</div>')
        if c.get("links"):
            ls = []
            for item in c["links"]:
                if isinstance(item, str) and item in BY_URL:
                    p = BY_URL[item]
                    ls.append(nc(p["name"]) if p["missing"] else f'<a href="{p["url"]}">{esc(p["name"])} {small("arrow")}</a>')
                else:
                    label, note = item
                    ls.append(f'<span class="nc">{esc(label)}<small>({esc(note)})</small></span>')
            # links to our own pages are main buttons, side by side (Legal documents)
            allpages = all(isinstance(i, str) and i in BY_URL and not BY_URL[i]["missing"] for i in c["links"])
            if allpages:
                parts.append('<div class="btns" style="margin-top:20px">' + "".join(btn(BY_URL[i]["name"], href=i) for i in c["links"]) + "</div>")
            else:
                parts.append(f'<div class="doclinks" style="margin-top:20px">{"".join(ls)}</div>')
        secs.append(f'<section class="doc__sec prose" id="{sid}"><h2>{esc(t)}</h2>{"".join(parts)}</section>')
    hero = s_hero(dict(variant="text", eyebrow=h.get("eyebrow"), h1=h["h1"], sub=h.get("sub"), buttons=h.get("buttons", [])), 4)
    final = s_final(spec["final"], 4) if spec.get("final") else ""
    return (hero + f'<section class="sec" style="padding-top:0"><div class="wrap doc"><nav class="doc__toc" aria-label="On this page"><b>On this page</b>{toc}</nav>'
            f'<div class="doc__body">{"".join(secs)}</div></div></section>' + final)

