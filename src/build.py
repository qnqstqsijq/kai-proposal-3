def render_sections(spec, pid):
    level = spec["level"]
    out = []
    for s in spec["sections"]:
        if s["t"] == "spread":
            out.append(s_spread(s, level)); continue
        if s["t"] == "story":
            out.append(s_story(s, level)); continue
        if s["t"] == "flow":
            out.append(s_flow(s, level)); continue
        if s["t"] == "security":
            out.append(s_security(s, level)); continue
        if s["t"] == "faq":
            out.append(s_faq(s, level, pid))
        else:
            out.append(SECTIONS[s["t"]](s, level))
    return "\n".join(out)

