def visual(v, level):
    if not v:
        return ""
    if isinstance(v, str):
        return VISUALS[v](level)
    if isinstance(v, dict) and v.get("preset"):          # a ready-made screen with its own still, e.g. dict(preset="convert", photo=...)
        return VISUALS[v["preset"]](level, photo=v.get("photo"))
    return vis_ui(v, level)

def alink(label, url, cls="lnk", arrow=True):
    p = BY_URL.get(url)
    if p and p["missing"]:
        return nc(label)
    tgt = ' target="_blank" rel="noopener"' if url.startswith("http") else ""
    if cls == "lnk":   # section call-to-action links use the main button (no secondary text links)
        return btn(label, href=url, extra=tgt)
    return f'<a class="{cls}" href="{url}"{tgt}>{esc(label)}{" " + small("arrow") if arrow else ""}</a>'

def buttons(items, level=4, d=0.3, cls="btns"):
    out = []
    for i, b in enumerate(items):
        label, h = b[0], b[1]
        kind = b[2] if len(b) > 2 else ("btn1" if i == 0 else "btn2")
        p = BY_URL.get(h)
        if p and p["missing"]:
            out.append(nc(label))
            continue
        out.append(btn(label, waitlist=(h == "waitlist"), href=h, kind=kind))
    return f'<div class="{cls}"{R(level, d)}>{"".join(out)}</div>' if out else ""

def head(s, level):
    if not (s.get("h2") or s.get("lead") or s.get("eyebrow")):
        return ""
    eb = ""  # no small titles above headings
    hh = f'<h2 class="h2"{R(level)}>{esc(s["h2"])}</h2>' if s.get("h2") else ""
    ld = f'<p class="lead"{R(level, .1)}>{esc(s["lead"])}</p>' if s.get("lead") else ""
    if s.get("h2") and s.get("line"):   # the section's note sits beside the title, not under the content
        # the section's buttons go with it, beside the title and above the content
        cta = buttons(s["ctas"], level, .2, "btns btns--head") if s.get("ctas") else ""
        ld = (f'<div class="sechead__side">{ld}' if ld else '<div class="sechead__side">') + f'<p class="sec-line sec-line--head"{R(level, .15)}>{esc(s["line"])}</p>{cta}</div>'
        s["_line_in_head"] = True
        s["_ctas_in_head"] = bool(cta)
    return f'<div class="sechead"><div class="stack" style="gap:16px">{eb}{hh}</div>{ld}</div>'

def tail(s, level):
    out = ""
    if s.get("line") and not s.get("_line_in_head"):
        out += f'<p class="sec-line"{R(level)}>{esc(s["line"])}</p>'
    if s.get("risk"):
        out += f'<p class="risk">{esc(s["risk"])}</p>'
