def pick_scenes(titles):
    used, out = set(), []
    for t in titles:
        words = re.findall(r"[a-z]+", (t or "").lower())
        k = next((sc for sc, keys in SCENE_WORDS if sc not in used and any(w.startswith(key) for w in words for key in keys)), None)
        k = k or next((sc for sc in SCENES if sc not in used), SCENES[len(out) % len(SCENES)])
        used.add(k); out.append(k)
    return out

