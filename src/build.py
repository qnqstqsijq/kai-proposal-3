def nc(label):
    return f'<span class="nc">{esc(label)}<small>(no-content)</small></span>'

def link(page, label=None, current=None, cls=""):
    label = label or page["label"]
    if page["missing"]:
        return nc(label)
    cur = ' aria-current="page"' if current == page["url"] else ""
    c = f' class="{cls}"' if cls else ""
    return f'<a href="{page["url"]}"{c}{cur}>{esc(label)}</a>'

def R(level, d=0.0):
    """Scroll-reveal attributes for level 2 and 3 pages."""
    if level > 3:
        return ""
    return f' data-r style="--d:{d:g}"' if d else " data-r"

