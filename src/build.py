# Banners and imagery (stage photos, photo cards, article images) show the homepage's animated cubes video
# as a placeholder until final imagery arrives. Portraits (/assets/p9-*) are left as they are.
CUBES = "/assets/kai-cubes-h264.mp4"
IMG_TAG = re.compile(r'<img\b([^>]*?)\ssrc="(/assets/(?:media|site/img)/[^"]+)"([^>]*)>')

def cubes(doc):
    def sub(m):
        if "data-photo" in m.group(0):   # article and post photos stay photos
            return m.group(0)
        attrs = re.sub(r'\s(?:alt|loading|width|height)="[^"]*"', "", m.group(1) + m.group(3)).strip()
        attrs = (" " + attrs) if attrs else ""
        return f'<video{attrs} src="{CUBES}" muted loop playsinline autoplay preload="metadata" aria-hidden="true"></video>'
    return IMG_TAG.sub(sub, doc)

# ---------- write ----------
def write(url, doc):
    doc = cubes(doc)
    path = os.path.join(ROOT, "404.html") if url == "/404" else os.path.join(ROOT, url.strip("/"), "index.html")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
    return os.path.relpath(path, ROOT)

